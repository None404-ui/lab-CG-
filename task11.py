def triangle_normal(x0, y0, z0, x1, y1, z1, x2, y2, z2):
    # Вычисление нормали к поверхности треугольника
    
    # Первый вектор: от вершины 2 к вершине 1
    v1_x = x1 - x2
    v1_y = y1 - y2
    v1_z = z1 - z2
    
    # Второй вектор: от вершины 0 к вершине 1
    v2_x = x1 - x0
    v2_y = y1 - y0
    v2_z = z1 - z0
    
    # Векторное произведение: n = v1 × v2
    n_x = v1_y * v2_z - v1_z * v2_y
    n_y = v1_z * v2_x - v1_x * v2_z
    n_z = v1_x * v2_y - v1_y * v2_x
    
    return n_x, n_y, n_z






